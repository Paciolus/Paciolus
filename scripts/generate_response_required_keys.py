#!/usr/bin/env python3
"""Write the frontend's list of required response keys from the OpenAPI snapshot.

Sprint 890 (CEO brief 15C, review ST-10): the upload hooks cast each response to its TypeScript
type without checking it. This writes, for each upload endpoint, the top-level keys its published
response schema marks required, so the hooks can refuse a response that lacks them. Run after
regenerating ``scripts/openapi-snapshot.json``:

    python scripts/generate_response_required_keys.py          # write
    python scripts/generate_response_required_keys.py --check  # exit 1 if out of date

``backend/tests/test_sprint_890_response_required_keys.py`` runs the check.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SNAPSHOT = REPO / "scripts" / "openapi-snapshot.json"
OUTPUT = REPO / "frontend" / "src" / "types" / "generated" / "responseRequiredKeys.ts"

ENDPOINTS = (
    "/audit/ap-payments",
    "/audit/ar-aging",
    "/audit/bank-reconciliation",
    "/audit/fixed-assets",
    "/audit/inventory-testing",
    "/audit/journal-entries",
    "/audit/payroll-testing",
    "/audit/revenue-testing",
    "/audit/three-way-match",
)


def render() -> str:
    spec = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    schemas = spec["components"]["schemas"]
    lines = [
        "/**",
        " * GENERATED by scripts/generate_response_required_keys.py from scripts/openapi-snapshot.json.",
        " * Do not edit by hand. Sprint 890 (15C): the top-level keys each upload endpoint's response",
        " * schema marks required; utils/checkedResponse.ts refuses a response that lacks one.",
        " */",
        "export const RESPONSE_REQUIRED_KEYS: Record<string, readonly string[]> = {",
    ]
    for endpoint in ENDPOINTS:
        schema_ref = spec["paths"][endpoint]["post"]["responses"]["200"]["content"][
            "application/json"
        ]["schema"]
        name = schema_ref["$ref"].rsplit("/", 1)[-1]
        required = sorted(schemas[name].get("required", []))
        keys = ", ".join(f"'{k}'" for k in required)
        lines.append(f"  '{endpoint}': [{keys}], // {name}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(
                f"{OUTPUT.relative_to(REPO)} is out of date; run scripts/generate_response_required_keys.py"
            )
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
