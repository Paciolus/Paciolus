#!/usr/bin/env python3
"""Write frontend/src/content/tool-catalog.generated.ts from backend/tools_registry.py.

Sprint 891 (CEO brief 16A, review ST-07): the registry lists the tools, but the dashboard, the
activity feed and the engagement workspace each kept their own table, and the six most recently
promoted tools were missing from some. The frontend tables now derive from this generated file.

    python scripts/generate_tool_catalog_ts.py          # write
    python scripts/generate_tool_catalog_ts.py --check  # exit 1 if out of date

``backend/tests/test_sprint_891_tool_catalog.py`` runs the check.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUTPUT = REPO / "frontend" / "src" / "content" / "tool-catalog.generated.ts"
sys.path.insert(0, str(REPO / "backend"))


def render() -> str:
    from tools_registry import MARKETING_AUDIT_TOOL_COUNT, TOOLS

    entries = []
    for t in TOOLS:
        entries.append(
            {
                "slug": t.slug,
                "displayName": t.display_name,
                "shortLabel": t.short_label,
                "href": t.href,
                "category": t.category,
                "isMarketingAuditTool": t.is_marketing_audit_tool,
                "dashboard": (
                    {"description": t.dashboard_description, "icon": t.dashboard_icon}
                    if t.dashboard_description
                    else None
                ),
            }
        )
    body = json.dumps(entries, indent=2, ensure_ascii=False)
    marketed = [t.slug for t in TOOLS if t.is_marketing_audit_tool]
    return (
        "/**\n"
        " * GENERATED by scripts/generate_tool_catalog_ts.py from backend/tools_registry.py.\n"
        " * Do not edit by hand. Sprint 891 (16A): one catalog for the dashboard, the activity feed and\n"
        " * the engagement workspace.\n"
        " */\n"
        "export interface CatalogTool {\n"
        "  slug: string\n"
        "  displayName: string\n"
        "  shortLabel: string\n"
        "  href: string | null\n"
        "  category: 'Core Analysis' | 'Testing Suite' | 'Advanced'\n"
        "  isMarketingAuditTool: boolean\n"
        "  dashboard: { description: string; icon: string } | null\n"
        "}\n\n"
        f"export const TOOL_CATALOG: readonly CatalogTool[] = {body}\n\n"
        f"export const MARKETING_AUDIT_TOOL_COUNT = {MARKETING_AUDIT_TOOL_COUNT}\n\n"
        f"export const MARKETING_AUDIT_TOOL_SLUGS: readonly string[] = {json.dumps(marketed)}\n"
    )


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(
                f"{OUTPUT.relative_to(REPO)} is out of date; run scripts/generate_tool_catalog_ts.py"
            )
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
