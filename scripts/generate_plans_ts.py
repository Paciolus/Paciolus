#!/usr/bin/env python3
"""Write frontend/src/content/plans.generated.ts from backend/shared/plans.json.

Sprint 891 (CEO brief 16B, review ST-06): prices, seat rates, limits and gates were authored
separately in the backend and in several frontend files. The plan file is the one source; the
frontend reads it through this generated module.

    python scripts/generate_plans_ts.py          # write
    python scripts/generate_plans_ts.py --check  # exit 1 if out of date

``backend/tests/test_sprint_891_plan_file.py`` runs the check.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SOURCE = REPO / "backend" / "shared" / "plans.json"
OUTPUT = REPO / "frontend" / "src" / "content" / "plans.generated.ts"


def render() -> str:
    plans = json.loads(SOURCE.read_text(encoding="utf-8"))
    plans.pop("_comment", None)
    body = json.dumps(plans, indent=2)
    return (
        "/**\n"
        " * GENERATED by scripts/generate_plans_ts.py from backend/shared/plans.json. Do not edit by hand.\n"
        " * Sprint 891 (16B): the one source for plan prices (cents), seat rates, limits and gates.\n"
        " * 0 for uploads_per_month or max_clients means unlimited; an empty tools_allowed or formats_allowed\n"
        " * list means all.\n"
        " */\n"
        "export type PlanTier = 'free' | 'solo' | 'professional' | 'enterprise'\n\n"
        "export interface PlanEntitlements {\n"
        "  uploads_per_month: number\n"
        "  max_clients: number\n"
        "  tools_allowed: string[]\n"
        "  formats_allowed: string[]\n"
        "  max_team_seats: number\n"
        "  seats_included: number\n"
        "  pdf_export: boolean\n"
        "  excel_export: boolean\n"
        "  csv_export: boolean\n"
        "  workspace: boolean\n"
        "  priority_support: boolean\n"
        "  export_sharing: boolean\n"
        "  activity_logs: boolean\n"
        "  admin_dashboard: boolean\n"
        "  bulk_upload: boolean\n"
        "  custom_branding: boolean\n"
        "  share_ttl_hours: number\n"
        "}\n\n"
        "export interface PlanFile {\n"
        "  tiers: Record<PlanTier, { price_cents: { monthly: number; annual: number }; entitlements: PlanEntitlements }>\n"
        "  seat_price_cents: Record<'professional' | 'enterprise', { monthly: number; annual: number }>\n"
        "}\n\n"
        f"export const PLANS: PlanFile = {body}\n"
    )


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(
                f"{OUTPUT.relative_to(REPO)} is out of date; run scripts/generate_plans_ts.py"
            )
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
