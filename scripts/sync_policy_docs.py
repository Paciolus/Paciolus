#!/usr/bin/env python3
"""
Sprint 862 — publish the compliance documents on the website.

`docs/04-compliance/` is the single source for the Security Policy, the
Subprocessor List and the Data Handling Architecture. The frontend cannot read
that folder at request time (Vercel builds from `frontend/`, and every page is
rendered per request for the CSP nonce), so this script copies the three
documents into a generated TypeScript module the site renders from.

`backend/tests/test_policy_docs_published.py` fails CI if the generated module
differs from the documents — edit the markdown, then run:

    python scripts/sync_policy_docs.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DOCS = REPO_ROOT / "docs" / "04-compliance"
OUTPUT = REPO_ROOT / "frontend" / "src" / "content" / "policies.generated.ts"

# export name -> (source file, site route)
PUBLISHED = {
    "SECURITY_POLICY_MD": ("SECURITY_POLICY.md", "/security"),
    "SUBPROCESSOR_LIST_MD": ("SUBPROCESSOR_LIST.md", "/subprocessors"),
    "DATA_HANDLING_ARCHITECTURE_MD": ("DATA_HANDLING_ARCHITECTURE.md", "/data-handling"),
}


def render() -> str:
    lines = [
        "// GENERATED by scripts/sync_policy_docs.py from docs/04-compliance/ — do not edit.",
        "// Edit the markdown and re-run the script; test_policy_docs_published.py checks they match.",
        "",
    ]
    for name, (filename, _route) in PUBLISHED.items():
        text = (DOCS / filename).read_text(encoding="utf-8").replace("\r\n", "\n")
        lines.append(f"export const {name} = {json.dumps(text, ensure_ascii=False)}")
        lines.append("")
    lines.append("/** Published documents: source filename → site route. Links between them are rewritten to these routes. */")
    routes = {filename: route for filename, route in PUBLISHED.values()}
    lines.append(f"export const POLICY_ROUTES: Record<string, string> = {json.dumps(routes, indent=2)}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
