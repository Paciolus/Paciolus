/**
 * Methodology sources — what each Paciolus test does and where the rule comes from.
 *
 * Paciolus is not an authority on accounting. It shares what the authorities
 * say, conveniently, and is explicit about which numbers are its own. For every
 * tool and test this catalog states the rule applied, the kind of source behind
 * it, and the authorities (if any) it draws on.
 *
 * Contract (enforced by backend/tests/test_methodology_sources.py and
 * backend/tests/test_citation_consistency.py):
 *  - every `sources` entry is a code registered in backend/standards_registry.py;
 *  - every marketing audit tool in backend/tools_registry.py has an entry
 *    (`toolKey` = registry slug, `toolName` = registry display name);
 *  - `toolKey`, `test`, `kind` and `sources` each stay on one line with
 *    single-quoted strings, so the backend test can parse this file.
 *
 * Citation policy: a rule is attributed to an authority only when we are
 * confident the authority says it, at the level of the standard (never invented
 * paragraph numbers). Every threshold, weight, band or cut-off that does not come
 * from a statute or standard is a `convention`, and its `note` says so.
 */

export type SourceKind =
  /** A standard or statute requires or defines it (e.g. a filing threshold, a classification rule). */
  | 'requirement'
  /** A standard or authoritative guide describes it as an indicator or procedure, without mandating the test. */
  | 'guidance'
  /** A published statistical or forensic method (e.g. Benford MAD bands, modified z-score). */
  | 'published-method'
  /** A Paciolus choice: thresholds, weights, tier bands, cut-offs. */
  | 'convention'

export interface MethodologyRule {
  /** Test ID and name as the engine reports it. */
  test: string
  /** What the test flags, in plain English, with its key thresholds. */
  rule: string
  kind: SourceKind
  /** Codes from backend/standards_registry.py. For a `convention`, empty or the standard that frames it. */
  sources: string[]
  /** True when a user can change the threshold for a run in the app today. */
  configurable?: boolean
  /** Which numbers are Paciolus defaults, and any caveat about the citation. */
  note?: string
}

export interface ToolMethodology {
  /** Slug in backend/tools_registry.py (or a shared, non-tool key). */
  toolKey: string
  toolName: string
  rules: MethodologyRule[]
}

